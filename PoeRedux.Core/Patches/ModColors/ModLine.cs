namespace PoeRedux.Patches.ModColors;

/// <summary>
/// One mod line Color Mods can recolor: a description block of the game's stat description files.
/// </summary>
/// <param name="Key">First stat id of the block; the patch matches blocks on it.</param>
/// <param name="Text">The English text with # for numbers.</param>
/// <param name="Sample">The English text with the largest value a mod rolls, for previews.</param>
/// <param name="Category">Monsters, Players, Area, Map boss, Rewards, Strongbox, Expedition or Altar.</param>
public sealed record ModLine(string Key, string Text, string Sample, string Category);

/// <summary>Mod lines per game. The lists are generated by tools/ModCatalogGen from the game files.</summary>
public static partial class ModLineCatalog
{
    public static IReadOnlyList<ModLine> For(Models.PoeGame game) => game == Models.PoeGame.PoE2 ? Poe2 : Poe1;
}
